#!/usr/bin/env bash

set -euo pipefail

readonly GENERATED_MARKER='<!-- Generated by APM CLI from .apm/ primitives -->'
readonly PROJECT_DOC_MAX_BYTES='131072'

usage() {
    cat <<'EOF'
Usage: scripts/bootstrap-global.sh [--update]

Install this repository's APM manifest at user scope and generate the Codex
and GitHub Copilot instruction files.

Options:
  --update  Refresh global dependencies before compiling instructions.
  -h, --help
            Show this help text.
EOF
}

die() {
    printf 'Error: %s\n' "$*" >&2
    exit 1
}

is_apm_generated() {
    local path=$1

    [ ! -L "$path" ] || return 1
    [ -f "$path" ] || return 1

    awk -v marker="$GENERATED_MARKER" '
        NR <= 6 && $0 == marker { found = 1 }
        END { exit(found ? 0 : 1) }
    ' "$path"
}

backup_hand_authored_file() {
    local path=$1
    local timestamp=$2
    local backup_path
    local counter=0

    if [ ! -e "$path" ] && [ ! -L "$path" ]; then
        return
    fi

    if is_apm_generated "$path"; then
        return
    fi

    backup_path="${path}.backup-${timestamp}"
    while [ -e "$backup_path" ] || [ -L "$backup_path" ]; do
        counter=$((counter + 1))
        backup_path="${path}.backup-${timestamp}.${counter}"
    done

    mv "$path" "$backup_path"
    printf 'Backed up hand-authored file: %s\n' "$backup_path"
}

set_codex_project_doc_limit() {
    local config_path=$1
    local config_dir
    local temp_path

    config_dir=$(dirname "$config_path")
    mkdir -p "$config_dir"

    if [ -L "$config_path" ]; then
        die "Refusing to replace symlinked Codex configuration: $config_path"
    fi

    if [ ! -e "$config_path" ]; then
        printf 'project_doc_max_bytes = %s\n' "$PROJECT_DOC_MAX_BYTES" > "$config_path"
        return
    fi

    [ -f "$config_path" ] || die "Codex configuration is not a regular file: $config_path"

    temp_path=$(mktemp "${config_path}.tmp.XXXXXX")
    if awk -v value="$PROJECT_DOC_MAX_BYTES" '
        BEGIN {
            in_top_level = 1
            wrote_setting = 0
        }
        {
            if (in_top_level && $0 ~ /^[[:space:]]*\[/) {
                if (!wrote_setting) {
                    print "project_doc_max_bytes = " value
                    print ""
                    wrote_setting = 1
                }
                in_top_level = 0
            }

            if (in_top_level && $0 ~ /^[[:space:]]*project_doc_max_bytes[[:space:]]*=/) {
                if (!wrote_setting) {
                    print "project_doc_max_bytes = " value
                    wrote_setting = 1
                }
                next
            }

            print
        }
        END {
            if (!wrote_setting) {
                print "project_doc_max_bytes = " value
            }
        }
    ' "$config_path" > "$temp_path"; then
        mv "$temp_path" "$config_path"
    else
        rm -f "$temp_path"
        die "Failed to update Codex configuration: $config_path"
    fi
}

update=false
case ${1-} in
    '')
        ;;
    --update)
        update=true
        ;;
    -h|--help)
        usage
        exit 0
        ;;
    *)
        usage >&2
        exit 2
        ;;
esac

[ "$#" -le 1 ] || {
    usage >&2
    exit 2
}

command -v apm >/dev/null 2>&1 || die 'APM CLI is not available on PATH.'

script_dir=$(CDPATH='' cd -- "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)
repo_root=$(CDPATH='' cd -- "$script_dir/.." && pwd -P)
manifest_path="$repo_root/apm.yml"
home_path=${HOME:?HOME must be set.}
global_apm_dir="$home_path/.apm"
codex_dir="$home_path/.codex"
copilot_dir="$home_path/.copilot"
timestamp=$(date -u '+%Y%m%d-%H%M%S')

[ -f "$manifest_path" ] || die "APM manifest not found: $manifest_path"

apm --version

mkdir -p "$global_apm_dir" "$codex_dir" "$copilot_dir"
[ ! -L "$global_apm_dir/apm.yml" ] || die "Refusing to replace symlinked global APM manifest: $global_apm_dir/apm.yml"
[ ! -L "$codex_dir/config.toml" ] || die "Refusing to replace symlinked Codex configuration: $codex_dir/config.toml"
backup_hand_authored_file "$codex_dir/AGENTS.md" "$timestamp"
backup_hand_authored_file "$copilot_dir/copilot-instructions.md" "$timestamp"
backup_hand_authored_file "$copilot_dir/AGENTS.md" "$timestamp"

cp "$manifest_path" "$global_apm_dir/apm.yml"
set_codex_project_doc_limit "$codex_dir/config.toml"

if [ "$update" = true ]; then
    apm update --global --yes
else
    apm install --global
fi

(
    cd "$global_apm_dir"
    apm compile --target codex --single-agents --output "$codex_dir/AGENTS.md"
    apm compile --target copilot --single-agents --output "$copilot_dir/copilot-instructions.md"
)

printf '%s\n' 'Global APM configuration is ready.'
printf '%s\n' 'Set GITHUB_TOKEN in your runtime environment to use the GitHub MCP server.'
printf '%s\n' 'Start new Codex and Copilot sessions to load the updated configuration.'
