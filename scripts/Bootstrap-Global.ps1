<#
.SYNOPSIS
Deploys this repository's reviewed APM baseline at user scope.

.DESCRIPTION
Preflights the reviewed manifest, lockfile, local sources, required tools, and
managed destinations; creates a complete timestamped rollback snapshot; runs a
frozen global installation; deploys the four local skills; and compiles Codex
and Copilot instructions through dry-run validation before writing them.

An existing github-mcp-server entry is recycled only when every Codex setting
matches the default APM-owned definition. Any failure after mutation begins
restores the snapshot automatically. Successful snapshots are retained for
manual rollback.

.EXAMPLE
./scripts/Bootstrap-Global.ps1

Deploys the reviewed global baseline.

.EXAMPLE
./scripts/Bootstrap-Global.ps1 -WhatIf

Runs preflight checks and describes the deployment without changing the user
profile.

.OUTPUTS
None. The script writes deployment status to the information stream.

.NOTES
The script supports Windows PowerShell 5.1 and PowerShell 7. It never reads,
writes, or displays GITHUB_TOKEN and does not manage project_doc_max_bytes or
~/.copilot/AGENTS.md.
#>
[CmdletBinding(SupportsShouldProcess = $true, ConfirmImpact = 'Medium')]
param()

Set-StrictMode -Version 2.0
$ErrorActionPreference = 'Stop'

$script:GeneratedMarker = '<!-- Generated by APM CLI from .apm/ primitives -->'
$script:GithubMcpName = 'github-mcp-server'
$script:GithubMcpUrl = 'https://api.githubcopilot.com/mcp/'
$script:BackupNamespace = 'agent-engineering-baseline'
$script:LocalSkills = @(
    'a11y'
    'agent-safety'
    'ansible'
    'powershell-module-engineering'
)
$script:ManagedSkills = @(
    'a11y'
    'agent-safety'
    'ansible'
    'powershell-module-engineering'
    'code-simplification'
    'dependabot'
    'git-commit'
    'github-actions-hardening'
    'msgraph'
)

function Test-ReparsePoint {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [System.IO.FileSystemInfo]$Item
    )

    return (($Item.Attributes -band [System.IO.FileAttributes]::ReparsePoint) -ne 0)
}

function Test-PathWithoutReparsePoint {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$Path,

        [Parameter(Mandatory)]
        [ValidateSet('File', 'Directory')]
        [string]$PathType,

        [Parameter()]
        [switch]$AllowMissing,

        [Parameter()]
        [switch]$Recurse
    )

    $item = Get-Item -LiteralPath $Path -Force -ErrorAction SilentlyContinue
    if ($null -eq $item) {
        if ($AllowMissing.IsPresent) {
            return $true
        }
        return $false
    }

    if (Test-ReparsePoint -Item $item) {
        return $false
    }

    if ($PathType -eq 'File') {
        return (-not $item.PSIsContainer)
    }
    if (-not $item.PSIsContainer) {
        return $false
    }

    if ($Recurse.IsPresent) {
        $linkedItem = Get-ChildItem -LiteralPath $Path -Force -Recurse `
            -Attributes ReparsePoint -ErrorAction Stop |
            Select-Object -First 1
        return ($null -eq $linkedItem)
    }
    return $true
}

function Assert-PathWithoutReparsePoint {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$Path,

        [Parameter(Mandatory)]
        [ValidateSet('File', 'Directory')]
        [string]$PathType,

        [Parameter()]
        [switch]$AllowMissing,

        [Parameter()]
        [switch]$Recurse,

        [Parameter(Mandatory)]
        [string]$Description
    )

    if (-not (Test-PathWithoutReparsePoint -Path $Path -PathType $PathType `
            -AllowMissing:$AllowMissing -Recurse:$Recurse)) {
        throw "$Description is missing, has the wrong type, or contains a reparse point: $Path"
    }
}

function Test-ApmGeneratedFile {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$Path
    )

    if (-not (Test-PathWithoutReparsePoint -Path $Path -PathType File -AllowMissing)) {
        return $false
    }
    if (-not [System.IO.File]::Exists($Path)) {
        return $false
    }

    $lineNumber = 0
    foreach ($line in [System.IO.File]::ReadLines($Path)) {
        $lineNumber++
        if ($line -ceq $script:GeneratedMarker) {
            return $true
        }
        if ($lineNumber -ge 6) {
            break
        }
    }
    return $false
}

function Get-ProjectDocSetting {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$Path
    )

    if (-not [System.IO.File]::Exists($Path)) {
        return
    }

    foreach ($line in [System.IO.File]::ReadLines($Path)) {
        if ($line -match '^\s*\[') {
            break
        }
        if ($line -match '^\s*project_doc_max_bytes\s*=') {
            Write-Output $line
        }
    }
}

function Test-DefaultGithubMcpConfiguration {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [object]$Configuration
    )

    $expectedTopLevel = @(
        'disabled_reason', 'disabled_tools', 'enabled', 'enabled_tools', 'name',
        'startup_timeout_sec', 'tool_timeout_sec', 'transport'
    ) -join ','
    $actualTopLevel = @($Configuration.PSObject.Properties.Name | Sort-Object) -join ','
    if ($actualTopLevel -cne $expectedTopLevel) {
        return $false
    }

    $expectedTransport = @(
        'bearer_token_env_var', 'env_http_headers', 'http_headers',
        'http_headers_helper', 'type', 'url'
    ) -join ','
    $actualTransport = @($Configuration.transport.PSObject.Properties.Name | Sort-Object) -join ','

    return (
        $actualTransport -ceq $expectedTransport -and
        $Configuration.name -ceq $script:GithubMcpName -and
        $Configuration.enabled -eq $true -and
        $null -eq $Configuration.disabled_reason -and
        $null -eq $Configuration.enabled_tools -and
        $null -eq $Configuration.disabled_tools -and
        $null -eq $Configuration.startup_timeout_sec -and
        $null -eq $Configuration.tool_timeout_sec -and
        $Configuration.transport.type -ceq 'streamable_http' -and
        $Configuration.transport.url -ceq $script:GithubMcpUrl -and
        $Configuration.transport.bearer_token_env_var -ceq 'GITHUB_TOKEN' -and
        $null -eq $Configuration.transport.http_headers -and
        $null -eq $Configuration.transport.env_http_headers -and
        $null -eq $Configuration.transport.http_headers_helper
    )
}

function Invoke-ExternalCommand {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$Executable,

        [Parameter(Mandatory)]
        [string[]]$ArgumentList,

        [Parameter()]
        [string]$WorkingDirectory
    )

    $pushed = $false
    try {
        if (-not [string]::IsNullOrWhiteSpace($WorkingDirectory)) {
            Push-Location -LiteralPath $WorkingDirectory
            $pushed = $true
        }
        & $Executable @ArgumentList
        if ($LASTEXITCODE -ne 0) {
            $renderedArguments = $ArgumentList -join ' '
            throw "Native command failed with exit code ${LASTEXITCODE}: $Executable $renderedArguments"
        }
    }
    finally {
        if ($pushed) {
            Pop-Location
        }
    }
}

function Copy-ManagedPath {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$Source,

        [Parameter(Mandatory)]
        [string]$Destination
    )

    $parentPath = Split-Path -Parent $Destination
    if (-not (Test-Path -LiteralPath $parentPath -PathType Container)) {
        $null = New-Item -ItemType Directory -Path $parentPath -Force
    }
    Copy-Item -LiteralPath $Source -Destination $Destination -Recurse -Force
}

function Remove-ManagedPath {
    [CmdletBinding(SupportsShouldProcess = $true, ConfirmImpact = 'Low')]
    param(
        [Parameter(Mandatory)]
        [string]$Path
    )

    if ((Test-Path -LiteralPath $Path) -and $PSCmdlet.ShouldProcess($Path, 'Remove managed path')) {
        Remove-Item -LiteralPath $Path -Recurse -Force
    }
}

function Set-ManagedPath {
    [CmdletBinding(SupportsShouldProcess = $true, ConfirmImpact = 'Low')]
    param(
        [Parameter(Mandatory)]
        [string]$Source,

        [Parameter(Mandatory)]
        [string]$Destination
    )

    if ($PSCmdlet.ShouldProcess($Destination, 'Replace managed path')) {
        $stagedPath = '{0}.agent-baseline-stage-{1}' -f $Destination, [Guid]::NewGuid().ToString('N')
        Copy-ManagedPath -Source $Source -Destination $stagedPath
        try {
            Remove-ManagedPath -Path $Destination -Confirm:$false
            Move-Item -LiteralPath $stagedPath -Destination $Destination
        }
        finally {
            if (Test-Path -LiteralPath $stagedPath) {
                Remove-ManagedPath -Path $stagedPath -Confirm:$false
            }
        }
    }
}

function Get-DirectoryInventory {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$Path
    )

    $root = [System.IO.Path]::GetFullPath($Path).TrimEnd(
        [System.IO.Path]::DirectorySeparatorChar,
        [System.IO.Path]::AltDirectorySeparatorChar
    )
    $items = @(Get-ChildItem -LiteralPath $root -Force -Recurse | Sort-Object -Property FullName)
    foreach ($item in $items) {
        $relativePath = $item.FullName.Substring($root.Length).TrimStart(
            [System.IO.Path]::DirectorySeparatorChar,
            [System.IO.Path]::AltDirectorySeparatorChar
        )
        if ($item.PSIsContainer) {
            Write-Output "D`t$relativePath"
        }
        else {
            $hash = (Get-FileHash -LiteralPath $item.FullName -Algorithm SHA256).Hash
            Write-Output "F`t$relativePath`t$hash"
        }
    }
}

function Test-DirectoryContentEqual {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$ReferencePath,

        [Parameter(Mandatory)]
        [string]$DifferencePath
    )

    if (-not (Test-Path -LiteralPath $ReferencePath -PathType Container) -or
        -not (Test-Path -LiteralPath $DifferencePath -PathType Container)) {
        return $false
    }

    $reference = @(Get-DirectoryInventory -Path $ReferencePath)
    $difference = @(Get-DirectoryInventory -Path $DifferencePath)
    return (($reference -join "`n") -ceq ($difference -join "`n"))
}

function Test-LockfileContentEqual {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$ReferencePath,

        [Parameter(Mandatory)]
        [string]$DifferencePath
    )

    if (-not [System.IO.File]::Exists($ReferencePath) -or
        -not [System.IO.File]::Exists($DifferencePath)) {
        return $false
    }

    $reference = @([System.IO.File]::ReadAllLines($ReferencePath) | Where-Object { $_ -notmatch '^generated_at:' })
    $difference = @([System.IO.File]::ReadAllLines($DifferencePath) | Where-Object { $_ -notmatch '^generated_at:' })
    return (($reference -join "`n") -ceq ($difference -join "`n"))
}

function Save-GlobalSnapshotPath {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$HomePath,

        [Parameter(Mandatory)]
        [string]$RelativePath,

        [Parameter(Mandatory)]
        [string]$SnapshotRoot,

        [Parameter(Mandatory)]
        [string]$InventoryPath,

        [Parameter(Mandatory)]
        [string]$AbsentPath
    )

    $sourcePath = Join-Path -Path $HomePath -ChildPath $RelativePath
    if (Test-Path -LiteralPath $sourcePath) {
        Add-Content -LiteralPath $InventoryPath -Value "present`t$RelativePath" -Encoding UTF8
        Copy-ManagedPath -Source $sourcePath -Destination (Join-Path $SnapshotRoot $RelativePath)
    }
    else {
        Add-Content -LiteralPath $InventoryPath -Value "absent`t$RelativePath" -Encoding UTF8
        Add-Content -LiteralPath $AbsentPath -Value $RelativePath -Encoding UTF8
    }
}

function Restore-GlobalSnapshot {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$HomePath,

        [Parameter(Mandatory)]
        [string]$SnapshotRoot,

        [Parameter(Mandatory)]
        [string]$InventoryPath
    )

    foreach ($line in [System.IO.File]::ReadAllLines($InventoryPath)) {
        if ([string]::IsNullOrWhiteSpace($line)) {
            continue
        }
        $fields = $line -split "`t", 2
        $status = $fields[0].TrimStart([char]0xFEFF)
        $relativePath = $fields[1]
        $destinationPath = Join-Path -Path $HomePath -ChildPath $relativePath
        Remove-ManagedPath -Path $destinationPath -Confirm:$false
        if ($status -ceq 'present') {
            Copy-ManagedPath -Source (Join-Path $SnapshotRoot $relativePath) -Destination $destinationPath
        }
    }
}

