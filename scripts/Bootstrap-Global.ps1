<#
.SYNOPSIS
Installs and transactionally deploys the reviewed global APM baseline.

.DESCRIPTION
Installs the repository-pinned APM CLI when needed, preflights the
reviewed manifest, lockfile, local sources, and managed destinations, creates a
complete timestamped rollback snapshot, runs a frozen global installation,
deploys the local skills, and compiles Codex and Copilot instructions through
dry-run validation before writing them.

Any failure after profile mutation begins restores the snapshot automatically.
Successful snapshots are retained for manual rollback.

.EXAMPLE
./scripts/Bootstrap-Global.ps1

Deploys the reviewed global baseline.

.EXAMPLE
./scripts/Bootstrap-Global.ps1 -WhatIf

Runs preflight checks and describes the deployment without changing the user
profile.

.OUTPUTS
None. The script writes deployment status to the information stream.

.NOTES
The script supports Windows PowerShell 5.1 and PowerShell 7. It does not manage
Codex or Copilot configuration files or ~/.copilot/AGENTS.md.
#>
[CmdletBinding(SupportsShouldProcess = $true, ConfirmImpact = 'Medium')]
param()

Set-StrictMode -Version 2.0
$ErrorActionPreference = 'Stop'

$script:GeneratedMarker = '<!-- Generated by APM CLI from .apm/ primitives -->'
$script:BackupNamespace = 'agent-engineering-baseline'
$script:LocalSkills = @(
    'a11y'
    'agent-safety'
    'ansible'
    'powershell-pester-6'
    'powershell-module-engineering'
)
$script:ManagedSkills = @(
